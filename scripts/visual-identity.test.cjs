const assert=require('node:assert/strict');const fs=require('node:fs');
const css=fs.readFileSync('styles.css','utf8'),html=fs.readFileSync('index.html','utf8'),svg=fs.readFileSync('steroid-icon.svg','utf8'),manifest=JSON.parse(fs.readFileSync('manifest.webmanifest','utf8'));
for(const color of ['#0B4D3B','#F5E8D5','#78A893','#1A1A1A'])assert(css.includes(color),'Missing brand color '+color);
for(const selector of ['.immersive-shell.is-welcome','.immersive-shell.is-onboard','.immersive-shell.is-auth','.hero','.tabbar','.exercise','.stat','.edit-day','.rest-timer'])assert(css.includes(selector),'Missing view '+selector);
assert(html.includes('fonts.googleapis.com/css2?family=Montserrat'));
assert(html.includes('steroid-icon.svg'));
assert(svg.includes('viewBox="0 0 158 160"'));
assert.equal(manifest.theme_color,'#0B4D3B');
assert(manifest.icons.some(x=>x.src==='./steroid-icon.svg'));
const favicon=fs.readFileSync('favicon.svg','utf8'),app=fs.readFileSync('app.js','utf8');
assert(favicon.includes('viewBox="0 0 128 128"'));
assert(favicon.includes('<circle'),'Favicon must be kettlebell O');
assert(!favicon.includes('<rect'),'Favicon must not have background square');
assert(svg.includes('<path'),'PWA icon must be vector artwork');
assert(app.includes('class="brand official-brand"'),'Header must use official wordmark image');
assert(app.includes('class="fit-wordmark official-wordmark"'),'Welcome must use official wordmark image');
assert(app.includes('class="answer-brand-icon"'),'Questionnaire uses vector icons');
assert(html.includes('href="./favicon.svg"'),'Favicon points to dedicated O');
assert(css.includes('.fit-answers{gap:10px}'),'Questionnaire spacing is compact');
console.log('Visual identity and crisp logo tests passed.');
