const assert=require('node:assert/strict'),fs=require('node:fs');
const progression=require('../sport-progression.js');
const ex={sets:3,reps:'8–12'};
const rows=(reps,completed=true)=>reps.map((r,i)=>({set_number:i+1,reps:r,weight:40,completed}));
assert.deepEqual(progression.repRange('8–12'),{min:8,max:12});
assert.equal(progression.repRange('30–45 s'),null);
assert.equal(progression.evaluate(ex,rows([12,12]),{}).status,'insufficient');
assert.equal(progression.evaluate(ex,rows([12,11,12]),{}).status,'reps');
assert.equal(progression.evaluate(ex,rows([12,12,12]),{}).status,'verify');
assert.equal(progression.evaluate(ex,rows([12,12,12]),{technique:true,rir:0}).status,'verify');
assert.equal(progression.evaluate(ex,rows([12,12,12]),{technique:false,rir:2}).status,'verify');
const good=progression.evaluate(ex,rows([12,12,12]),{technique:true,rir:2});
assert.equal(good.status,'increase');
assert.equal(good.suggestedWeight,41.25);
assert.equal(progression.evaluate({...ex,reps:'Gainage 30–45 s'},rows([12,12,12]),{}).status,'not_applicable');
const app=fs.readFileSync('app.js','utf8'),html=fs.readFileSync('index.html','utf8');
assert(html.includes('src="./sport-progression.js"'));
assert(app.includes("data-action=\"verify-rir\""));
assert(app.includes('previousExerciseLogs(S.day,ex.name)'));
console.log('Double progression/RIR: tests réussis.');
